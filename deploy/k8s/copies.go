// Package k8s holds the Kubernetes manifests of the IMS. Its
// role configuration files and DNS zones are copies of those in
// deploy/compose, made by go generate, because kustomize does not read
// files outside its own directory. A copy differs from its original
// only by the table in changes.go.
package k8s

//go:generate go run ./gencopies

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"go.yaml.in/yaml/v3"
)

// The directories of the originals and the copies, relative to
// deploy/k8s, where go generate runs.
const (
	ComposeDir = "../compose"
	ConfigDir  = "base/config"
	ZoneDir    = "dns"
)

// KindEnvironment holds the values of the kind cluster that the
// manifests depend on (environments/kind/kustomization.yaml). The zone
// takes the name server's address from it.
const KindEnvironment = "environments/kind"

// EnvironmentConfigMap is the name of the ConfigMap of values that each
// environment defines and the components read.
const EnvironmentConfigMap = "ims-environment"

// GenerateCommand is what a person runs, from the root of the
// repository, after changing deploy/compose or changes.go.
const GenerateCommand = "go generate ./deploy/k8s/..."

// A change is one entry of the table in changes.go.
type change struct {
	// file is the role file the change applies to. Empty applies it to
	// every role file that has the key.
	file string
	// key is a dotted path, with the index of an item of a sequence, as
	// in dashboard.ues.0.control.
	key string
	// comment, when not empty, replaces the comment lines right above
	// the key, or goes there when there are none.
	comment string
	// value, when not nil, replaces the value of the key.
	value any
	// remove takes the key and its value out, and leaves comment in
	// their place.
	remove bool
}

// Copies returns every copy, by its path relative to deploy/k8s, made
// from the role files and the zones in composeDir.
func Copies(composeDir string) (map[string][]byte, error) {
	nameServerAddress, err := environmentValue(KindEnvironment, nameServerAddressKey)
	if err != nil {
		return nil, err
	}
	copies := map[string][]byte{}
	used := make([]bool, len(changes))

	roleFiles, err := filepath.Glob(filepath.Join(composeDir, "*.yaml"))
	if err != nil {
		return nil, err
	}
	for _, path := range roleFiles {
		name := filepath.Base(path)
		src, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		var mine []change
		for i, c := range changes {
			if c.file == name || (c.file == "" && hasKey(src, c.key)) {
				mine = append(mine, c)
				used[i] = true
			}
		}
		out, err := applyChanges(src, mine)
		if err != nil {
			return nil, fmt.Errorf("deploy/compose/%s: %w", name, err)
		}
		copies[ConfigDir+"/"+name] = append(header("#", "deploy/compose/"+name), out...)
	}
	for i, c := range changes {
		if !used[i] {
			return nil, fmt.Errorf("changes.go: %s %s matches no role file in deploy/compose", c.file, c.key)
		}
	}

	zones, err := filepath.Glob(filepath.Join(composeDir, "dns", "*.zone"))
	if err != nil {
		return nil, err
	}
	for _, path := range zones {
		name := filepath.Base(path)
		src, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		out := src
		if name == homeZone {
			if out, err = toServices(src, nameServerAddress); err != nil {
				return nil, fmt.Errorf("deploy/compose/dns/%s: %w", name, err)
			}
		}
		copies[ZoneDir+"/"+name] = append(header(";", "deploy/compose/dns/"+name), out...)
	}
	return copies, nil
}

// header says where a copy comes from, so that nobody edits it by hand.
func header(comment, original string) []byte {
	return fmt.Appendf(nil, "%[1]s Generated by %[2]q from\n%[1]s %[3]s and\n%[1]s deploy/k8s/changes.go. Change those, not this file.\n\n",
		comment, GenerateCommand, original)
}

// An edit replaces lines[start:end] of a file with lines.
type edit struct {
	start, end int
	lines      []string
}

// applyChanges edits the text of a YAML file, so that its comments,
// the order of its keys and the style of every value it does not
// change stay as they are. Encoding a yaml.Node again would change
// quoting and spacing. The YAML parser only finds where each key is.
func applyChanges(src []byte, cs []change) ([]byte, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(src, &doc); err != nil {
		return nil, err
	}
	lines := strings.SplitAfter(string(src), "\n")
	var edits []edit
	for _, c := range cs {
		key, value, err := lookup(&doc, c.key)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", c.key, err)
		}
		e, err := c.edits(lines, key, value)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", c.key, err)
		}
		edits = append(edits, e...)
	}
	// From the bottom up, so that the line numbers of the edits not yet
	// made stay right. Of two edits at one line, the one that replaces
	// lines goes first and the one that only inserts goes above it.
	slices.SortFunc(edits, func(a, b edit) int {
		if a.start != b.start {
			return b.start - a.start
		}
		return b.end - a.end
	})
	for i, e := range edits {
		if i > 0 && e.end > edits[i-1].start {
			return nil, errors.New("two changes touch the same lines")
		}
		lines = slices.Replace(lines, e.start, e.end, e.lines...)
	}
	out := []byte(strings.Join(lines, ""))
	if err := yaml.Unmarshal(out, &yaml.Node{}); err != nil {
		return nil, fmt.Errorf("the changed file is no longer YAML: %w", err)
	}
	return out, nil
}

func hasKey(src []byte, path string) bool {
	var doc yaml.Node
	if yaml.Unmarshal(src, &doc) != nil {
		return false
	}
	_, _, err := lookup(&doc, path)
	return err == nil
}

// lookup finds the key at a dotted path and its value.
func lookup(doc *yaml.Node, path string) (key, value *yaml.Node, err error) {
	if len(doc.Content) == 0 {
		return nil, nil, errors.New("empty document")
	}
	node := doc.Content[0]
	for _, part := range strings.Split(path, ".") {
		key = nil
		switch node.Kind {
		case yaml.MappingNode:
			for i := 0; i+1 < len(node.Content); i += 2 {
				if node.Content[i].Value == part {
					key, node = node.Content[i], node.Content[i+1]
					break
				}
			}
			if key == nil {
				return nil, nil, fmt.Errorf("no key %q", part)
			}
		case yaml.SequenceNode:
			i, err := strconv.Atoi(part)
			if err != nil || i < 0 || i >= len(node.Content) {
				return nil, nil, fmt.Errorf("no item %q", part)
			}
			node = node.Content[i]
		default:
			return nil, nil, fmt.Errorf("%q is inside a scalar", part)
		}
	}
	if key == nil {
		return nil, nil, errors.New("the path ends at an item of a sequence, not at a key")
	}
	return key, node, nil
}

// edits turns a change into edits of the lines of the file. It relies
// on the block style of deploy/compose: a key starts its own line, or
// follows "- " as the first key of an item, and whatever belongs to it
// is indented further.
func (c change) edits(lines []string, key, value *yaml.Node) ([]edit, error) {
	at := key.Line - 1
	indent := key.Column - 1
	line := lines[at]
	if !strings.HasPrefix(line[indent:], key.Value+":") {
		return nil, errors.New("the key is not written as a plain key")
	}
	ownLine := strings.TrimSpace(line[:indent]) == ""
	if (c.comment != "" || c.remove) && !ownLine {
		return nil, errors.New("only a key on its own line can have its comment changed or be removed")
	}

	commentStart := at
	for commentStart > 0 && isCommentAt(lines[commentStart-1], indent) {
		commentStart--
	}
	valueEnd := at + 1
	for i := at + 1; i < len(lines); i++ {
		text := strings.TrimSpace(lines[i])
		if text == "" {
			continue
		}
		in := len(lines[i]) - len(strings.TrimLeft(lines[i], " "))
		compactItem := in == indent && value.Kind == yaml.SequenceNode && strings.HasPrefix(text, "-")
		if in <= indent && !compactItem {
			break
		}
		valueEnd = i + 1
	}

	comment := commentLines(strings.Repeat(" ", indent), "#", c.comment)
	if c.remove {
		return []edit{{commentStart, valueEnd, comment}}, nil
	}
	var edits []edit
	if c.comment != "" {
		edits = append(edits, edit{commentStart, at, comment})
	}
	if c.value != nil {
		v, err := valueLines(line[:indent]+key.Value+":", indent, c.value)
		if err != nil {
			return nil, err
		}
		edits = append(edits, edit{at, valueEnd, v})
	}
	return edits, nil
}

func isCommentAt(line string, indent int) bool {
	text := strings.TrimLeft(line, " ")
	return strings.HasPrefix(text, "#") && len(line)-len(text) == indent
}

// commentLines writes text as comment lines, each after pad and mark.
func commentLines(pad, mark, text string) []string {
	if text == "" {
		return nil
	}
	var lines []string
	for _, l := range strings.Split(text, "\n") {
		lines = append(lines, strings.TrimRight(pad+mark+" "+l, " ")+"\n")
	}
	return lines
}

// valueLines writes a scalar after the key, and a sequence or a mapping
// in block style below it.
func valueLines(keyText string, indent int, value any) ([]string, error) {
	b, err := yaml.Marshal(value)
	if err != nil {
		return nil, err
	}
	text := strings.TrimRight(string(b), "\n")
	switch reflect.ValueOf(value).Kind() {
	case reflect.Slice, reflect.Map, reflect.Struct:
	default:
		if !strings.Contains(text, "\n") {
			return []string{keyText + " " + text + "\n"}, nil
		}
	}
	lines := []string{keyText + "\n"}
	pad := strings.Repeat(" ", indent+2)
	for _, l := range strings.Split(text, "\n") {
		lines = append(lines, pad+l+"\n")
	}
	return lines, nil
}

// aRecord is an A record as deploy/compose/dns writes them, with the
// columns lined up: "hss       IN A     172.28.0.10".
var aRecord = regexp.MustCompile(`^(\S+)(\s+IN\s+)A(\s+)(\S+)\s*$`)

// toServices makes the home network zone of Kubernetes from that of
// Docker Compose (changes.go).
func toServices(src []byte, nameServerAddress string) ([]byte, error) {
	lines := strings.SplitAfter(string(src), "\n")
	first := 0
	for first < len(lines) && strings.HasPrefix(lines[first], ";") {
		first++
	}
	out := commentLines("", ";", homeZoneHeader)
	var last []string
	for _, line := range lines[first:] {
		m := aRecord.FindStringSubmatch(strings.TrimRight(line, "\n"))
		switch {
		case m == nil:
			out = append(out, line)
		case m[1] == nameServer:
			if last != nil {
				return nil, fmt.Errorf("%q has two A records", m[1])
			}
			// One space before and after the type, as components/name-server
			// writes it with the address of another environment.
			last = append(commentLines("", ";", nameServerComment),
				strings.TrimRight(m[1]+m[2], " ")+" A "+nameServerAddress+"\n")
		case strings.Contains(m[1], ".") || m[1] == "@":
			return nil, fmt.Errorf("%q: only the A record of a single label can become a CNAME to a Service", m[1])
		default:
			// The target starts in the column of the address.
			pad := strings.Repeat(" ", max(1, len("A")+len(m[3])-len("CNAME")))
			out = append(out, m[1]+m[2]+"CNAME"+pad+m[1]+serviceDomain+"\n")
		}
	}
	if last == nil {
		return nil, fmt.Errorf("no A record for the name server %q", nameServer)
	}
	out = append(out, "\n")
	out = append(out, last...)
	return []byte(strings.Join(out, "")), nil
}

// environmentValues reads the ConfigMap ims-environment from the
// kustomization of an environment (environments/<name>): its literals,
// and the files of its envs. A cloud environment keeps its values in
// such a file, values.local.env, which Git ignores because the values
// are the person's own (.gitignore). For it this reads the committed
// example next to it, values.local.env.example, so that go generate and
// the tests give the same result on every machine.
func environmentValues(dir string) (map[string]string, error) {
	path := filepath.Join(dir, "kustomization.yaml")
	src, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var k struct {
		ConfigMapGenerator []struct {
			Name     string
			Literals []string
			Envs     []string
		} `yaml:"configMapGenerator"`
	}
	if err := yaml.Unmarshal(src, &k); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	for _, g := range k.ConfigMapGenerator {
		if g.Name != EnvironmentConfigMap {
			continue
		}
		values := map[string]string{}
		for _, l := range g.Literals {
			key, value, ok := strings.Cut(l, "=")
			if !ok {
				return nil, fmt.Errorf("%s: %q is not key=value", path, l)
			}
			values[key] = value
		}
		for _, env := range g.Envs {
			if err := readEnvFile(filepath.Join(dir, env+ExampleSuffix), values); err != nil {
				return nil, err
			}
		}
		return values, nil
	}
	return nil, fmt.Errorf("%s: no ConfigMap %s", path, EnvironmentConfigMap)
}

// ExampleSuffix ends the name of the committed example of a file that
// Git ignores, such as environments/aws/values.local.env.example.
const ExampleSuffix = ".example"

// readEnvFile adds the values of an env file of kustomize to values. As
// kustomize reads it, a line is KEY=value, and a line that starts with
// "#" after any spaces is a comment; a "#" after a value belongs to the
// value.
func readEnvFile(path string, values map[string]string) error {
	src, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	for i, line := range strings.Split(string(src), "\n") {
		line = strings.TrimLeft(strings.TrimSuffix(line, "\r"), " \t")
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		key, value, ok := strings.Cut(line, "=")
		if !ok {
			return fmt.Errorf("%s:%d: %q is not KEY=value", path, i+1, line)
		}
		// kustomize refuses a key that two sources define.
		if _, defined := values[key]; defined {
			return fmt.Errorf("%s:%d: %s is defined twice", path, i+1, key)
		}
		values[key] = value
	}
	return nil
}

// environmentValue is one value of environmentValues.
func environmentValue(dir, key string) (string, error) {
	values, err := environmentValues(dir)
	if err != nil {
		return "", err
	}
	v, ok := values[key]
	if !ok {
		return "", fmt.Errorf("%s: the ConfigMap %s has no %s", dir, EnvironmentConfigMap, key)
	}
	return v, nil
}
