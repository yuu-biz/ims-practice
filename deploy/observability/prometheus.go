// Package observability holds the Compose fragment, the Prometheus
// configuration and the Grafana provisioning that show the metrics of
// the IMS. The ims job of prometheus/prometheus.yml is made
// from the root compose.yaml by go generate; the rest of that file is
// written by hand.
package observability

//go:generate go run ./genprometheus

import (
	"errors"
	"fmt"
	"strings"

	"go.yaml.in/yaml/v3"
)

// The files the generator reads and writes, relative to
// deploy/observability, where go generate runs.
const (
	RootCompose   = "../../compose.yaml"
	PrometheusYML = "prometheus/prometheus.yml"
)

// GenerateCommand is what a person runs, from the root of the
// repository, after adding a node to compose.yaml or changing
// MetricsPort. "go generate ./deploy/..." runs it as well, together
// with that of deploy/k8s.
const GenerateCommand = "go generate ./deploy/observability/..."

// MetricsPort is the port on which every IMS node is assumed to serve
// internal/metrics at /metrics, on the listener of its maintenance
// API. No specification gives a port for this; 8085 is this project's
// choice.
const MetricsPort = 8085

// The lines between these two markers in prometheus.yml belong to the
// generator. Everything outside them is kept as it is.
var (
	beginMarker = fmt.Sprintf("# BEGIN generated by %q from compose.yaml. Do not edit these lines.", GenerateCommand)
	endMarker   = "# END generated"
)

// composeService holds what decides whether a service of compose.yaml
// is an IMS node.
type composeService struct {
	Build    any      `yaml:"build"`
	Profiles []string `yaml:"profiles"`
}

// Nodes returns, in the order of compose.yaml, the services that are
// IMS nodes: those built from the Dockerfile at the root of the
// repository, which runs one or more roles, and that start
// with "docker compose up", that is, that are in no profile. The UE
// simulators are built from the same Dockerfile but only start in a
// profile, and they are not network nodes. dns, capture and peer run
// other images.
func Nodes(compose []byte) ([]string, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(compose, &doc); err != nil {
		return nil, err
	}
	if len(doc.Content) == 0 || doc.Content[0].Kind != yaml.MappingNode {
		return nil, errors.New("compose.yaml is not a mapping")
	}
	top := doc.Content[0]
	var services *yaml.Node
	for i := 0; i+1 < len(top.Content); i += 2 {
		if top.Content[i].Value == "services" {
			services = top.Content[i+1]
		}
	}
	if services == nil || services.Kind != yaml.MappingNode {
		return nil, errors.New("compose.yaml has no services")
	}
	var nodes []string
	for i := 0; i+1 < len(services.Content); i += 2 {
		name := services.Content[i].Value
		// Decode resolves the "<<: *ims-node" merge key, which is where
		// most nodes get their build.
		var s composeService
		if err := services.Content[i+1].Decode(&s); err != nil {
			return nil, fmt.Errorf("service %s: %w", name, err)
		}
		if buildsRoot(s.Build) && len(s.Profiles) == 0 {
			nodes = append(nodes, name)
		}
	}
	if len(nodes) == 0 {
		return nil, errors.New("compose.yaml has no service built from the root of the repository")
	}
	return nodes, nil
}

// buildsRoot tells whether a build of compose.yaml uses the root of the
// repository as its context, in the short form (build: .) or the long
// one (build: {context: .}).
func buildsRoot(build any) bool {
	switch b := build.(type) {
	case string:
		return b == "." || b == "./"
	case map[string]any:
		context, _ := b["context"].(string)
		return context == "." || context == "./"
	}
	return false
}

// imsJob writes the scrape configuration of the ims job, indented to
// sit under scrape_configs.
func imsJob(nodes []string) []string {
	lines := []string{
		"  - job_name: ims\n",
		"    metrics_path: /metrics\n",
		"    static_configs:\n",
	}
	for _, n := range nodes {
		lines = append(lines,
			fmt.Sprintf("      - targets: [\"%s:%d\"]\n", n, MetricsPort),
			fmt.Sprintf("        labels: {node: %s}\n", n),
		)
	}
	return lines
}

// PrometheusConfig returns prometheus.yml as it should be: current,
// with the lines between the markers replaced by the ims job for the
// nodes of compose. The generator writes it and the test compares the
// file with it.
func PrometheusConfig(current, compose []byte) ([]byte, error) {
	nodes, err := Nodes(compose)
	if err != nil {
		return nil, err
	}
	lines := strings.SplitAfter(string(current), "\n")
	begin, end := -1, -1
	for i, l := range lines {
		switch strings.TrimSpace(l) {
		case beginMarker:
			if begin >= 0 {
				return nil, errors.New("two begin markers")
			}
			begin = i
		case endMarker:
			if end >= 0 {
				return nil, errors.New("two end markers")
			}
			end = i
		}
	}
	if begin < 0 || end < begin {
		return nil, fmt.Errorf("no lines between %q and %q", beginMarker, endMarker)
	}
	var out []string
	out = append(out, lines[:begin+1]...)
	out = append(out, imsJob(nodes)...)
	out = append(out, lines[end:]...)
	result := []byte(strings.Join(out, ""))
	if err := yaml.Unmarshal(result, &yaml.Node{}); err != nil {
		return nil, fmt.Errorf("the generated file is no longer YAML: %w", err)
	}
	return result, nil
}
